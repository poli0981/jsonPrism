// Release signing — loaded from `keystore.properties` at the gen/android root.
// That file (and the .jks it points to) is gitignored; it lives only on the
// maintainer's machine and is decoded from GitHub Secrets in CI. When it's
// absent (e.g. a contributor build) the release variant simply stays unsigned.
val keystorePropertiesFile = rootProject.file("keystore.properties")
val hasReleaseKeystore = keystorePropertiesFile.exists()
val keystoreProperties = Properties().apply {
    if (hasReleaseKeystore) {
        FileInputStream(keystorePropertiesFile).use { load(it) }
    }
}

